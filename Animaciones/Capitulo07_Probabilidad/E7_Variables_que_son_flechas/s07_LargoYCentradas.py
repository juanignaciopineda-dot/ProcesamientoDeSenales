"""Escena 07 — Largo, ortogonales y variables centradas; el ejemplo 6, 4, 3 como flechas."""
from comun.escena import *

O = (-4.6, -2.2)
O3 = np.array([O[0], O[1], 0.0])
OO = (-2.6, -2.2)


class LargoYCentradas(EscenaCurso):
    ESCENA = "07"

    def construct(self):
        self.ortogonales()
        self.centradas()
        self.ejemplo()
        self.wait(1.0)
        self.limpiar()

    def ortogonales(self):
        r1 = Text("Medias", color=INK).scale(0.6).move_to([-3.0, 3.4, 0])
        r2 = Text("Varianzas", color=INK).scale(0.6).move_to([0.3, 3.4, 0])
        r3 = Text("Covarianzas", color=INK).scale(0.6).move_to([3.7, 3.4, 0])
        X = flecha_c(OO, 2.8, 70, COL_U7)
        Y = flecha_c(OO, 3.0, 15, COL_V7)
        Y2 = flecha_c(OO, 2.8, 160, COL_V7)
        rx = MathTex("X", color=COL_U7).scale(1.0).move_to(X.get_end() + UP * 0.35)
        ry = MathTex("Y", color=COL_V7).scale(1.0).move_to(Y.get_end() + RIGHT * 0.35)
        ry2 = MathTex("Y", color=COL_V7).scale(1.0).move_to(Y2.get_end() + LEFT * 0.35)
        arco = arco7(OO, 70, 160, 0.9, AMBAR)
        n90 = Text("90°", color=AMBAR).scale(0.5).move_to(np.array([OO[0], OO[1], 0.0]) + np.array([-1.0, 1.2, 0]))
        l2 = MathTex(r"|X|^2", "=", "E[X^2]", color=TXT).scale(1.3).move_to([2.6, 1.9, 0])
        l2[0].set_color(COL_U7)
        l2[2].set_color(AMBAR)
        e0 = MathTex("E[XY]", "=", "0", color=TXT).scale(1.3).move_to([2.6, 0.7, 0])
        e0[2].set_color(VERDE)
        ort = self.palabra("Ortogonales", AMBAR, 0.9).move_to([2.6, -0.5, 0])
        nh = Text("No es una forma de hablar", color=INK, slant=ITALIC).scale(0.55).move_to([2.6, -1.6, 0])
        pl = MathTex("u", r"\cdot", "v", "=", "0", color=TXT).scale(1.0).move_to([2.6, -2.7, 0])
        pl[0].set_color(COL_U7)
        pl[2].set_color(COL_V7)
        pl[4].set_color(VERDE)
        pl_txt = Text("En el plano", color=INK).scale(0.5).next_to(pl, LEFT, buff=0.3)
        with self.narrar("b1"):
            self.en("solo")
            self.play(FadeIn(r1), FadeIn(r2), FadeIn(r3), run_time=self.dur(0.9))
            self.en("flechas")
            self.play(GrowArrow(X), GrowArrow(Y), FadeIn(rx), FadeIn(ry), run_time=self.dur(0.8))
            self.en("largo")
            self.play(FadeIn(l2[0]), run_time=self.dur(0.5))
            self.en("ex2")
            self.play(FadeIn(l2[1]), FadeIn(l2[2]), run_time=self.dur(0.5))
            self.en("cero")
            self.play(FadeIn(e0), run_time=self.dur(0.6))
            self.en("perp")
            self.play(Transform(Y, Y2), Transform(ry, ry2), Create(arco), FadeIn(n90), run_time=self.dur(1.0))
            self.en("ortog")
            self.pop(ort)
            self.en("nohabla")
            self.play(FadeIn(nh), run_time=self.dur(0.5))
            self.en("plano")
            self.play(FadeIn(pl), FadeIn(pl_txt), run_time=self.dur(0.5))

    def centradas(self):
        self.corte()
        # ejes con el origen marcado: las flechas empiezan desplazadas (en la media) y vuelven al origen
        OC = np.array([-3.4, -0.6, 0.0])
        eje_x = Arrow(OC + LEFT * 2.9, OC + RIGHT * 4.0, buff=0, color=INK, stroke_width=3,
                      max_tip_length_to_length_ratio=0.04)
        eje_y = Arrow(OC + DOWN * 2.7, OC + UP * 3.7, buff=0, color=INK, stroke_width=3,
                      max_tip_length_to_length_ratio=0.04)
        ejes_g = VGroup(eje_x, eje_y)
        cero = Dot(OC, radius=0.09, color=TXT)
        t_cero = MathTex("0", color=INK).scale(0.8).move_to(OC + np.array([-0.3, -0.3, 0.0]))
        sh = np.array([1.5, 0.8, 0.0])
        media = Dot(OC + sh, radius=0.1, color=AMBAR)
        t_media = Text("Media", color=AMBAR).scale(0.5).next_to(media, DOWN, buff=0.15)
        X = flecha_c(OC + sh, 2.6, 66, COL_U7)
        Y = flecha_c(OC + sh, 2.8, 14, COL_V7)
        rx = MathTex(r"X-\mu_X", color=COL_U7).scale(0.9).move_to(X.get_end() + UP * 0.4)
        ry = MathTex(r"Y-\mu_Y", color=COL_V7).scale(0.9).move_to(Y.get_end() + RIGHT * 0.8)
        cov = MathTex(r"E[(X-\mu_X)(Y-\mu_Y)]", "=", r"\sigma_{XY}", color=TXT).scale(1.0).move_to([2.8, 2.7, 0])
        cov[2].set_color(AMBAR)
        var = MathTex(r"|X-\mu_X|^2", "=", r"\sigma_X^2", color=TXT).scale(1.1).move_to([2.8, 1.4, 0])
        var[2].set_color(AMBAR)
        sx = MathTex(r"\sigma_X", color=AMBAR).scale(0.9)
        sy = MathTex(r"\sigma_Y", color=AMBAR).scale(0.9)
        prod = MathTex("u", r"\cdot", "v", "=", r"\sigma_{XY}", color=TXT).scale(1.5).move_to([2.8, -0.2, 0])
        prod[0].set_color(COL_U7)
        prod[2].set_color(COL_V7)
        prod[4].set_color(AMBAR)
        self.sh = sh
        with self.narrar("b2"):
            self.en("centrar")
            self.play(FadeIn(ejes_g), FadeIn(cero), FadeIn(t_cero), FadeIn(media), FadeIn(t_media),
                      GrowArrow(X), GrowArrow(Y), FadeIn(rx), FadeIn(ry), run_time=self.dur(0.9))
            self.en("restar")
            self.play(X.animate.shift(-sh), Y.animate.shift(-sh),
                      rx.animate.shift(-sh), ry.animate.shift(-sh),
                      FadeOut(media), FadeOut(t_media), run_time=self.dur(1.2))
            self.en("cov")
            self.play(FadeIn(cov), run_time=self.dur(1.0))
            self.en("var")
            self.play(FadeIn(var), run_time=self.dur(0.8))
            self.en("desv")
            sx.move_to(rx.get_center() + LEFT * 0.0 + UP * 0.0)
            self.play(Transform(rx, sx.move_to(X.get_end() + UP * 0.4)),
                      Transform(ry, sy.move_to(Y.get_end() + RIGHT * 0.5)), run_time=self.dur(0.8))
            self.en("prod")
            self.play(FadeIn(prod), run_time=self.dur(0.6))

    def ejemplo(self):
        self.corte()
        k = 1.3
        X = flecha_c(O, np.sqrt(6) * k, 52.2, COL_U7)
        Y = flecha_c(O, 2 * k, 0, COL_V7)
        t1 = MathTex(r"\sigma_X^2", "=", "6", color=TXT).scale(1.3).move_to([3.8, 2.6, 0])
        t2 = MathTex(r"\sigma_Y^2", "=", "4", color=TXT).scale(1.3).move_to([3.8, 1.5, 0])
        t3 = MathTex(r"\sigma_{XY}", "=", "3", color=TXT).scale(1.3).move_to([3.8, 0.4, 0])
        t1[0].set_color(COL_U7)
        t2[0].set_color(COL_V7)
        t3[0].set_color(AMBAR)
        lx = MathTex(r"\sqrt{6}\approx 2{,}45", color=COL_U7).scale(0.9).move_to(X.get_end() + UP * 0.4)
        ly = MathTex("2", color=COL_V7).scale(1.0).move_to(Y.get_end() + RIGHT * 0.35)
        pe = MathTex("X", r"\cdot", "Y", "=", "3", color=TXT).scale(1.4).move_to([3.8, -1.0, 0])
        pe[0].set_color(COL_U7)
        pe[2].set_color(COL_V7)
        pe[4].set_color(AMBAR)
        arco = arco7(O, 0, 52.2, 1.1, AMBAR)
        th = MathTex(r"\theta=\ ?", color=AMBAR).scale(0.9).move_to(O3 + np.array([1.9, 0.5, 0]))
        with self.narrar("b3"):
            self.en("ejemplo")
            self.play(FadeIn(t1), FadeIn(t2), FadeIn(t3), run_time=self.dur(0.6))
            self.en("v6")
            self.resaltar(t1, color=AMBAR, run_time=0.5)
            self.en("r6")
            self.play(GrowArrow(X), FadeIn(lx), run_time=self.dur(0.8))
            self.en("v4")
            self.resaltar(t2, color=AMBAR, run_time=0.5)
            self.en("l2")
            self.play(GrowArrow(Y), FadeIn(ly), run_time=self.dur(0.8))
            self.en("cov3")
            self.resaltar(t3, color=AMBAR, run_time=0.5)
            self.en("pe")
            self.play(FadeIn(pe), run_time=self.dur(0.6))
            self.en("dos")
            self.resaltar(X, Y, color=AMBAR, run_time=0.8)
            self.en("angulo")
            self.play(Create(arco), FadeIn(th), run_time=self.dur(0.8))

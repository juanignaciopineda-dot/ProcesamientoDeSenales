"""Escena 12 — El discriminante y la desigualdad de Cauchy-Schwarz."""
from comun.escena import *


class Discriminante(EscenaCurso):
    ESCENA = "12"

    def construct(self):
        self.discriminante()
        self.desigualdad()
        self.wait(1.0)
        self.limpiar()

    def discriminante(self):
        ec = MathTex(r"a\lambda^2+b\lambda+c=0", color=TXT).scale(1.1).move_to([-3.2, 3.1, 0])
        sol = MathTex(r"\lambda", "=", r"\tfrac{1}{2a}", r"\left(", r"-b\pm", r"\sqrt{b^2-4ac}", r"\right)", color=TXT)
        sol.scale(1.0).move_to([-3.2, 1.8, 0])
        sol[5].set_color(AMBAR)
        disc = Text("Discriminante", color=AMBAR, weight=BOLD).scale(0.6).move_to([-2.4, 0.5, 0])
        flecha_d = Arrow(disc.get_top() + UP * 0.05, sol[5].get_bottom() + DOWN * 0.2, buff=0.05, color=AMBAR, stroke_width=3)
        # tres parábolas
        p1 = parabola_l(centro=(2.4, 2.6), ancho=3.0, alto=1.7, fondo=-0.6, color=INK)
        p2 = parabola_l(centro=(2.4, 0.3), ancho=3.0, alto=1.7, fondo=0.0, color=INK)
        p3 = parabola_l(centro=(2.4, -2.0), ancho=3.0, alto=1.7, fondo=0.5, color=INK)
        e1 = MathTex(r"b^2-4ac>0", color=ROJO).scale(0.8).move_to([5.7, 2.6, 0])
        e2 = MathTex(r"b^2-4ac=0", color=AMBAR).scale(0.8).move_to([5.7, 0.3, 0])
        e3 = MathTex(r"b^2-4ac<0", color=VERDE).scale(0.8).move_to([5.7, -2.0, 0])
        d1 = VGroup(*[Dot(p1.L.p(x, 0), radius=0.1, color=ROJO) for x in (-np.sqrt(0.6 / 0.45), np.sqrt(0.6 / 0.45))])
        d2 = Dot(p2.L.p(0, 0), radius=0.1, color=AMBAR)
        ning = Text("Ningún punto", color=VERDE).scale(0.5).move_to([2.4, -3.2, 0])
        nopos = MathTex(r"b^2-4ac\ \le\ 0", color=VERDE).scale(1.5).move_to([-3.0, -2.2, 0])
        with self.narrar("b1"):
            self.en("ecuacion")
            self.play(FadeIn(ec), FadeIn(sol), run_time=self.dur(1.4))
            self.en("colegio")
            self.resaltar(ec, color=AMBAR, run_time=0.5)
            self.en("raiz")
            self.resaltar(sol[5], color=AMBAR, run_time=0.6)
            self.en("discri")
            self.play(FadeIn(disc), GrowArrow(flecha_d), run_time=self.dur(0.6))
            self.en("positivo")
            self.play(Create(p1.eje), Create(p1.curva), FadeIn(e1), run_time=self.dur(0.8))
            self.en("dos")
            self.play(FadeIn(d1), run_time=self.dur(0.4))
            self.en("cero")
            self.play(Create(p2.eje), Create(p2.curva), FadeIn(e2), run_time=self.dur(0.8))
            self.en("un")
            self.play(FadeIn(d2), run_time=self.dur(0.4))
            self.en("negativo")
            self.play(Create(p3.eje), Create(p3.curva), FadeIn(e3), run_time=self.dur(0.8))
            self.en("notoca")
            self.play(FadeIn(ning), run_time=self.dur(0.4))
            self.en("nocorta")
            self.play(Create(cruz(ROJO, 1.2).move_to([2.4, 2.8, 0])), p1.curva.animate.fade(0.7), run_time=self.dur(0.5))
            self.sfx("error")
            self.en("nopos")
            self.play(FadeIn(nopos), run_time=self.dur(0.5))
            self.sfx("pop")

    def desigualdad(self):
        self.corte()
        cond = MathTex(r"(-2E[UV])^2-4\,E[V^2]\,E[U^2]\ \le\ 0", color=TXT).scale(1.1).move_to([-2.4, 3.3, 0])
        simp = MathTex(r"E[UV]^2", r"\le", r"E[U^2]\,E[V^2]", color=TXT).scale(1.2).move_to([-2.4, 1.8, 0])
        simp[0].set_color(AMBAR)
        simp[2].set_color(COL_U7)
        nom = Text("Cauchy-Schwarz", color=AMBAR, weight=BOLD).scale(0.6).move_to([-2.4, 2.65, 0])
        cen = MathTex(r"\sigma_{XY}^2", r"\le", r"\sigma_X^2\,\sigma_Y^2", color=TXT).scale(1.2).move_to([-2.4, 0.6, 0])
        nun = MathTex(r"|\sigma_{XY}|", r"\le", r"\sigma_X\,\sigma_Y", color=TXT).scale(1.2).move_to([-2.4, -0.5, 0])
        rho = MathTex("-1", r"\le", r"\rho", r"\le", "1", color=AMBAR).scale(1.6).move_to([-2.4, -1.9, 0])
        flecha_r = Arrow([-2.4, -0.95, 0], [-2.4, -1.45, 0], buff=0.0, color=INK, stroke_width=3)
        gl = MathTex(r"g(\lambda)=6-6\lambda+4\lambda^2", color=TXT).scale(1.2).move_to([4.2, 1.8, 0])
        v60 = MathTex("36-96", "=", "-60", "<", "0", color=TXT).scale(1.1).move_to([4.2, 0.6, 0])
        v60[2].set_color(VERDE)
        par = parabola_l(centro=(4.2, -1.8), ancho=3.4, alto=2.0, fondo=0.6, color=VERDE)
        self.add(cond, simp, nom, cen, nun, rho, flecha_r, gl, v60)
        for m in (cond, simp, nom, cen, nun, rho, flecha_r, gl, v60):
            m.set_opacity(0)
        with self.narrar("b2"):
            self.en("condicion")
            self.play(cond.animate.set_opacity(1), run_time=self.dur(0.9))
            self.en("simplifica")
            self.play(simp.animate.set_opacity(1), run_time=self.dur(0.8))
            self.en("cs")
            self.play(nom.animate.set_opacity(1), run_time=self.dur(0.5))
            self.en("euv")
            self.resaltar(simp[0], color=AMBAR, run_time=0.6)
            self.en("eu2v2")
            self.resaltar(simp[2], color=AMBAR, run_time=0.6)
            self.en("centradas")
            self.play(cen.animate.set_opacity(1), run_time=self.dur(0.8))
            self.en("nunca")
            self.play(nun.animate.set_opacity(1), run_time=self.dur(0.8))
            self.en("esdecir")
            self.play(flecha_r.animate.set_opacity(1), run_time=self.dur(0.4))
            self.en("rho")
            self.play(rho.animate.set_opacity(1), run_time=self.dur(0.7))
            self.sfx("pop")
            self.en("numeros")
            self.play(gl.animate.set_opacity(1), run_time=self.dur(0.8))
            self.en("v60")
            self.play(v60.animate.set_opacity(1), run_time=self.dur(0.8))
            self.en("lejos")
            self.play(Create(par.eje), Create(par.curva), run_time=self.dur(0.8))

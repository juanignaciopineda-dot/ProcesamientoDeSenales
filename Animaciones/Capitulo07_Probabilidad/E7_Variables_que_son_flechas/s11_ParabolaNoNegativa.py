"""Escena 11 — Cauchy-Schwarz: g(λ) = E[(U − λV)²] es una parábola que no baja de cero."""
from comun.escena import *


class ParabolaNoNegativa(EscenaCurso):
    ESCENA = "11"

    def construct(self):
        self.planteo()
        self.desarrollo()
        self.wait(1.0)
        self.limpiar()

    def planteo(self):
        recta = Line([-6.2, 3.2, 0], [-2.2, 3.2, 0], color=INK, stroke_width=3)
        t_m1 = MathTex("-1", color=INK).scale(0.7).move_to([-6.2, 2.75, 0])
        t_p1 = MathTex("1", color=INK).scale(0.7).move_to([-2.2, 2.75, 0])
        t_cos = MathTex(r"\cos\theta", color=AMBAR).scale(0.9).move_to([-4.2, 3.75, 0])
        rho = MathTex(r"\rho", "=", r"\dfrac{\sigma_{XY}}{\sigma_X\,\sigma_Y}", color=TXT).scale(1.3).move_to([3.6, 3.0, 0])
        rho[0].set_color(AMBAR)
        dem = MathTex(r"\vert\rho\vert\le 1\ ?", color=AMBAR).scale(1.8).move_to([0, 1.4, 0])
        U = MathTex("U", color=COL_U7).scale(1.4).move_to([-5.4, -0.2, 0])
        V = MathTex("V", color=COL_V7).scale(1.4).move_to([-4.2, -0.2, 0])
        lam = MathTex(r"\lambda", color=AMBAR).scale(1.4).move_to([-3.0, -0.2, 0])
        g = oculta(MathTex(r"g(\lambda)", "=", "E[", r"(U-\lambda V)", "^2", "]", color=TXT)
                   .scale(1.2).move_to([2.6, -0.2, 0]))
        g[0].set_color(AMBAR)
        nunca = MathTex(r"g(\lambda)\ \ge\ 0", color=VERDE).scale(1.6).move_to([2.6, -1.8, 0])
        self.add(g)
        with self.narrar("b1"):
            self.en("coseno")
            self.play(Create(recta), FadeIn(t_m1), FadeIn(t_p1), FadeIn(t_cos), run_time=self.dur(0.8))
            self.en("esperanzas")
            self.play(FadeIn(rho), run_time=self.dur(0.9))
            self.en("demostrar")
            self.pop(dem)
            self.en("preciosa")
            self.resaltar(dem, color=AMBAR, run_time=0.6)
            self.en("uv")
            self.play(FadeIn(U), FadeIn(V), run_time=self.dur(0.6))
            self.en("lambda")
            self.play(FadeIn(lam), run_time=self.dur(0.5))
            self.en("g")
            self.play(*revelar(g[0], g[1], g[2], g[3]), run_time=self.dur(1.2))
            self.en("todo")
            self.play(*revelar(g[4], g[5]), run_time=self.dur(0.5))
            self.en("cuadrado")
            self.resaltar(g[4], color=AMBAR, escala=1.8, run_time=0.6)
            self.en("nunca")
            self.play(FadeIn(nunca), run_time=self.dur(0.5))
            self.sfx("pop")

    def desarrollo(self):
        self.corte()
        base = MathTex(r"(U-\lambda V)^2", color=TXT).scale(1.3).move_to([-3.4, 3.2, 0])
        t1 = MathTex("E[U^2]", color=COL_U7).scale(1.2).move_to([-3.4, 2.0, 0])
        t2 = MathTex(r"-\,2\lambda\,E[UV]", color=AMBAR).scale(1.2).move_to([-3.4, 0.9, 0])
        t3 = MathTex(r"+\,\lambda^2\,E[V^2]", color=COL_V7).scale(1.2).move_to([-3.4, -0.2, 0])
        par = parabola_l(centro=(3.4, -0.4), ancho=5.0, alto=3.4, fondo=0.4, color=AMBAR)
        glam = MathTex(r"g(\lambda)", color=AMBAR).scale(0.9).move_to([3.4, 2.6, 0])
        lam_ax = MathTex(r"\lambda", color=INK).scale(0.8).move_to([6.2, -0.8, 0])
        abc = MathTex(r"a\lambda^2", "+", r"b\lambda", "+", "c", color=TXT).scale(1.3).move_to([-3.4, -1.7, 0])
        abc[0].set_color(COL_V7)
        abc[2].set_color(AMBAR)
        abc[4].set_color(COL_U7)
        nunca = MathTex(r"g(\lambda)\ \ge\ 0", color=VERDE).scale(1.4).move_to([-3.4, -3.0, 0])
        with self.narrar("b2"):
            self.en("desarrolla")
            self.play(FadeIn(base), run_time=self.dur(0.6))
            self.en("t1")
            self.play(FadeIn(t1), run_time=self.dur(0.5))
            self.en("t2")
            self.play(FadeIn(t2), run_time=self.dur(0.5))
            self.en("t3")
            self.play(FadeIn(t3), run_time=self.dur(0.5))
            self.en("miras")
            self.play(FadeOut(base), run_time=self.dur(0.4))
            self.en("funcion")
            self.resaltar(t2, t3, color=AMBAR, run_time=0.6)
            self.en("parabola")
            self.play(Create(par.eje), Create(par.curva), FadeIn(glam), FadeIn(lam_ax), run_time=self.dur(1.2))
            self.en("abc")
            self.play(FadeIn(abc), run_time=self.dur(0.8))
            self.en("sabemos")
            self.resaltar(par.curva, color=AMBAR, run_time=0.6)
            self.en("nunca")
            self.play(par.curva.animate.set_color(VERDE), FadeIn(nunca), run_time=self.dur(0.7))

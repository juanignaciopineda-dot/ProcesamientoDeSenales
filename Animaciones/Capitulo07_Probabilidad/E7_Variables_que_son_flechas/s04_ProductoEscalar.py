"""Escena 04 — El producto escalar: suma de productos y largos por coseno (u = (3, 4), v = (4, 0))."""
from comun.escena import *

O = (-5.4, -2.4)
P = 0.72


class ProductoEscalar(EscenaCurso):
    ESCENA = "04"

    def construct(self):
        grilla = cuadricula7(O, P, 6, 6)
        u = vec7(O, 3, 4, P, COL_U7)
        v = vec7(O, 4, 0, P, COL_V7)
        lu = MathTex("u", color=COL_U7).scale(0.9).next_to(u.get_end(), UP, buff=0.12)
        lv = MathTex("v", color=COL_V7).scale(0.9).next_to(v.get_end(), RIGHT, buff=0.12)
        pe = MathTex("u", r"\cdot", "v", color=TXT).scale(1.5).move_to([2.8, 3.1, 0])
        pe[0].set_color(COL_U7)
        pe[2].set_color(COL_V7)
        capA = Text("Componente × componente", color=INK).scale(0.5).move_to([2.8, 2.2, 0])
        capB = Text("Y se suma", color=INK).scale(0.5).move_to([2.8, 1.6, 0])
        pares = MathTex("u=(3,4)", ",", "v=(4,0)", color=TXT).scale(0.95).move_to([2.8, 0.7, 0])
        pares[0].set_color(COL_U7)
        pares[2].set_color(COL_V7)
        cuenta = MathTex("3", r"\cdot", "4", "+", "4", r"\cdot", "0", color=TXT).scale(1.2).move_to([2.8, -0.4, 0])
        doce = MathTex("=", "12", color=TXT).scale(1.4).move_to([2.8, -1.5, 0])
        doce[1].set_color(AMBAR)
        arco = arco7(O, 0, 53.13, 1.0, AMBAR)
        th = MathTex(r"\theta", color=AMBAR).scale(0.8).move_to(punto7(O, 0, 0, P) + np.array([1.5, 0.45, 0]))
        largos = MathTex("|u|", r"\,", "|v|", color=TXT).scale(1.3).move_to([2.2, 3.1, 0])
        largos[0].set_color(COL_U7)
        largos[2].set_color(COL_V7)
        cosf = MathTex(r"\cos\theta", color=AMBAR).scale(1.3).next_to(largos, RIGHT, buff=0.25)
        c2 = MathTex("5", r"\cdot", "4", r"\cdot", r"\cos\theta", "=", "12", color=TXT).scale(1.2).move_to([2.8, 1.3, 0])
        c2[4].set_color(AMBAR)
        c6 = MathTex(r"\cos\theta", "=", num_tex(0.6), color=TXT).scale(1.5).move_to([2.8, -0.4, 0])
        c6[0].set_color(AMBAR)
        c6[2].set_color(AMBAR)
        g53 = MathTex(r"\theta\approx 53^\circ", color=AMBAR).scale(0.9).move_to([2.8, -1.6, 0])
        self.add(grilla, u, lu)
        with self.narrar("b1"):
            self.en("dos_flechas")
            self.play(GrowArrow(v), FadeIn(lv), run_time=self.dur(0.7))
            self.en("pe")
            self.pop(pe)
            self.en("mult")
            self.play(FadeIn(capA), run_time=self.dur(0.5))
            self.en("suma")
            self.play(FadeIn(capB), run_time=self.dur(0.5))
            self.en("pares")
            self.play(FadeIn(pares), run_time=self.dur(0.6))
            self.en("cuenta")
            self.play(FadeIn(cuenta, shift=UP * 0.2), run_time=self.dur(1.2))
            self.en("doce")
            self.play(FadeIn(doce), run_time=self.dur(0.4))
            self.sfx("pop")
            self.en("otra")
            self.play(FadeOut(pe), FadeOut(capA), FadeOut(capB), FadeOut(pares), FadeOut(cuenta),
                      FadeOut(doce), Create(arco), FadeIn(th), run_time=self.dur(0.8))
            self.en("largos")
            self.play(FadeIn(largos), run_time=self.dur(0.6))
            self.en("coseno")
            self.play(FadeIn(cosf), run_time=self.dur(0.5))
            self.resaltar(arco, color=AMBAR, run_time=0.5)
            self.en("cuenta2")
            self.play(FadeOut(largos), FadeOut(cosf), FadeIn(c2), run_time=self.dur(1.0))
            self.en("seis")
            self.play(FadeOut(c2), FadeIn(c6), run_time=self.dur(0.5))
            self.play(FadeIn(g53), run_time=0.4)
        self.wait(1.0)
        self.limpiar()

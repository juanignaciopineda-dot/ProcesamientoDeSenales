"""Escena 06 — El producto escalar entre variables aleatorias: E[XY] y sus tres reglas."""
from comun.escena import *


class ProductoDeVariables(EscenaCurso):
    ESCENA = "06"

    def construct(self):
        self.definicion()
        self.reglas()
        self.wait(1.0)
        self.limpiar()

    def definicion(self):
        hf = Text("Flechas", color=COL_U7, weight=BOLD).scale(0.7).move_to([-3.6, 3.2, 0])
        hv = Text("Variables aleatorias", color=COL_V7, weight=BOLD).scale(0.7).move_to([3.6, 3.2, 0])
        uv = MathTex("u", r"\cdot", "v", color=TXT).scale(1.5).move_to([-3.6, 2.0, 0])
        xy = MathTex("X", r"\cdot", "Y", color=TXT).scale(1.5).move_to([3.6, 2.0, 0])
        uv[0].set_color(COL_U7)
        uv[2].set_color(COL_V7)
        xy[0].set_color(COL_U7)
        xy[2].set_color(COL_V7)
        defin = oculta(MathTex("X", r"\cdot", "Y", "=", "E[XY]", color=TXT).scale(1.3).move_to([3.6, 0.7, 0]))
        defin[4].set_color(AMBAR)
        corr = Text("La correlación", color=AMBAR).scale(0.6).move_to([3.6, -0.3, 0])
        aprox = MathTex(r"\approx", color=TXT).scale(1.6).move_to([0, 2.0, 0])
        tach = cruz(ROJO, 0.7).move_to(aprox)
        mismas = Text("Mismas reglas", color=AMBAR, weight=BOLD).scale(0.65).move_to([-3.6, 0.7, 0])
        tres = self.palabra("Tres reglas", AMBAR, 1.1).move_to([0, -2.2, 0])
        with self.narrar("b1"):
            self.en("def")
            self.play(FadeIn(hf), FadeIn(hv), FadeIn(uv), FadeIn(xy), run_time=self.dur(0.7))
            self.en("esperanza")
            self.add(defin)
            self.play(*revelar(defin[0], defin[1], defin[2], defin[3]), run_time=0.4)
            self.play(*revelar(defin[4]), run_time=0.5)
            self.en("correlacion")
            self.play(FadeIn(corr), run_time=self.dur(0.5))
            self.en("parecido")
            self.play(FadeIn(aprox), run_time=0.3)
            self.play(Create(tach), run_time=0.4)
            self.sfx("error")
            self.en("reglas")
            self.play(FadeOut(aprox), FadeOut(tach), FadeIn(mismas), run_time=self.dur(0.5))
            self.en("tres")
            self.pop(tres)

    def reglas(self):
        self.corte()
        c1 = casilla7("1", (-5.6, 2.5), ancho=0.9)
        c2 = casilla7("2", (-5.6, 0.2), ancho=0.9)
        c3 = casilla7("3", (-5.6, -2.1), ancho=0.9)
        t1 = Text("No importa el orden", color=TXT).scale(0.6).move_to([-2.6, 2.5, 0])
        f1a = MathTex("E[XY]", color=TXT).scale(1.2).move_to([2.0, 2.5, 0])
        f1b = MathTex("=", "E[YX]", color=TXT).scale(1.2).next_to(f1a, RIGHT, buff=0.3)
        ok1 = tilde(VERDE, 0.8).next_to(f1b, RIGHT, buff=0.4)
        t2 = Text("Es lineal", color=TXT).scale(0.6).move_to([-3.4, 0.5, 0])
        comb = MathTex("Z", "=", "aX+bY", color=TXT).scale(0.95).move_to([-3.4, -0.3, 0])
        f2 = MathTex("E[ZW]", "=", "a\\,E[XW]", "+", "b\\,E[YW]", color=TXT).scale(0.95).move_to([2.6, 0.2, 0])
        lin = Text("Linealidad", color=AMBAR).scale(0.5).move_to([2.6, -0.7, 0])
        sub = Line(lin.get_corner(DL) + DOWN * 0.05, lin.get_corner(DR) + DOWN * 0.05, color=AMBAR, stroke_width=3)
        t3 = Text("Consigo misma", color=TXT).scale(0.6).move_to([-2.9, -2.1, 0])
        xx = MathTex("X", r"\cdot", "X", color=TXT).scale(1.1).move_to([-0.2, -2.1, 0])
        pos = MathTex(">", "0", color=VERDE).scale(1.1).next_to(xx, RIGHT, buff=0.2)
        ex2 = MathTex("E[X^2]", color=AMBAR).scale(1.2).move_to([3.0, -2.1, 0])
        par = parabola_l(centro=(5.6, -1.9), ancho=1.6, alto=1.0, fondo=0.35, color=AMBAR)
        oks = VGroup(tilde(VERDE, 0.8), tilde(VERDE, 0.8), tilde(VERDE, 0.8))
        oks[0].move_to([-4.85, 2.5, 0])
        oks[1].move_to([-4.85, 0.2, 0])
        oks[2].move_to([-4.85, -2.1, 0])
        with self.narrar("b2"):
            self.en("orden")
            self.play(FadeIn(c1), FadeIn(c2), FadeIn(c3), FadeIn(t1), run_time=self.dur(0.6))
            self.en("exy")
            self.play(FadeIn(f1a), run_time=self.dur(0.5))
            self.en("eyx")
            self.play(FadeIn(f1b), run_time=self.dur(0.5))
            self.play(FadeIn(ok1), run_time=0.3)
            self.en("lineal")
            self.play(FadeIn(t2), run_time=self.dur(0.4))
            self.en("combina")
            self.play(FadeIn(comb), run_time=self.dur(0.5))
            self.en("reparte")
            self.play(FadeIn(f2[0]), FadeIn(f2[1]), run_time=0.4)
            self.play(FadeIn(f2[2]), FadeIn(f2[3]), FadeIn(f2[4]), run_time=0.8)
            self.en("linealidad")
            self.play(FadeIn(lin), Create(sub), run_time=self.dur(0.5))
            self.en("tercera")
            self.play(FadeIn(t3), FadeIn(xx), run_time=self.dur(0.5))
            self.en("positivo")
            self.play(FadeIn(pos), run_time=self.dur(0.4))
            self.en("cuadrado")
            self.play(FadeIn(ex2), Create(par.eje), Create(par.curva), run_time=self.dur(0.9))
            self.en("cumplen")
            self.play(c1.marco.animate.set_stroke(VERDE), c2.marco.animate.set_stroke(VERDE), c3.marco.animate.set_stroke(VERDE), run_time=self.dur(0.6))
            self.sfx("exito")

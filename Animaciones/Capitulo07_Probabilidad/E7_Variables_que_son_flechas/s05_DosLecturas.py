"""Escena 05 — Dos lecturas del producto escalar (largo y perpendicular) y el salto a las variables."""
from comun.escena import *

O = (-5.0, -2.0)
P = 0.62


class DosLecturas(EscenaCurso):
    ESCENA = "05"

    def construct(self):
        self.lecturas()
        self.salto()
        self.wait(1.0)
        self.limpiar()

    def lecturas(self):
        c1 = casilla7("1", (2.8, 3.1), ancho=1.2)
        c2 = casilla7("2", (2.8, 0.6), ancho=1.2)
        grilla = cuadricula7(O, P, 6, 6)
        u = vec7(O, 3, 4, P, COL_U7)
        uu = MathTex("u", r"\cdot", "u", color=TXT).scale(1.3).move_to([4.6, 3.1, 0])
        uu[0].set_color(COL_U7)
        uu[2].set_color(COL_U7)
        l2 = MathTex("=", r"|u|^2", color=TXT).scale(1.3).next_to(uu, RIGHT, buff=0.2)
        cu = MathTex("3", r"\cdot", "3", "+", "4", r"\cdot", "4", color=TXT).scale(1.1).move_to([3.9, 2.0, 0])
        v25 = MathTex("=", "25", "=", "5^2", color=TXT).scale(1.1).move_to([3.9, 1.35, 0])
        v25[1].set_color(AMBAR)
        v25[3].set_color(AMBAR)
        # segunda lectura: dos flechas en ángulo recto
        a = vec7(O, 3, 0, P, COL_U7)
        b = vec7(O, 0, 3, P, COL_V7)
        sq = Square(side_length=0.35, color=AMBAR, stroke_width=3).move_to(punto7(O, 0, 0, P) + np.array([0.18, 0.18, 0]))
        n90 = MathTex(r"\cos 90^\circ=0", color=AMBAR).scale(0.95).move_to([3.9, -0.6, 0])
        ce = MathTex("u", r"\cdot", "v", "=", "0", color=TXT).scale(1.4).move_to([3.9, -1.7, 0])
        ce[0].set_color(COL_U7)
        ce[2].set_color(COL_V7)
        ce[4].set_color(VERDE)
        regla = Text("Producto 0  ⇔  perpendiculares", color=VERDE, weight=BOLD).scale(0.6).move_to([2.6, -3.2, 0])
        with self.narrar("b1"):
            self.en("dos")
            self.play(FadeIn(c1), FadeIn(c2), run_time=self.dur(0.5))
            self.en("primera")
            self.play(FadeIn(grilla), GrowArrow(u), c1.marco.animate.set_stroke(AMBAR), run_time=self.dur(0.8))
            self.en("consigo")
            self.play(FadeIn(uu), run_time=self.dur(0.5))
            self.en("largo2")
            self.play(FadeIn(l2), run_time=self.dur(0.5))
            self.en("cuenta")
            self.play(FadeIn(cu), run_time=self.dur(0.8))
            self.en("v25")
            self.play(FadeIn(v25), run_time=self.dur(0.6))
            self.sfx("pop")
            self.en("segunda")
            self.play(FadeOut(u), FadeOut(uu), FadeOut(l2), FadeOut(cu), FadeOut(v25),
                      c1.marco.animate.set_stroke(INK), c2.marco.animate.set_stroke(AMBAR),
                      GrowArrow(a), GrowArrow(b), run_time=self.dur(0.8))
            self.en("perp")
            self.play(Create(sq), run_time=self.dur(0.4))
            self.en("noventa")
            self.play(FadeIn(n90), run_time=self.dur(0.5))
            self.en("cero")
            self.play(FadeIn(ce), run_time=self.dur(0.5))
            self.en("regla")
            self.pop(regla)

    def salto(self):
        self.corte()
        r1 = Text("Largo", color=AMBAR, weight=BOLD).scale(0.75).move_to([-4.2, 2.6, 0])
        r2 = Text("Ángulo", color=AMBAR, weight=BOLD).scale(0.75).move_to([-0.2, 2.6, 0])
        r3 = Text("Perpendicular", color=AMBAR, weight=BOLD).scale(0.75).move_to([4.2, 2.6, 0])
        src = MathTex("u", r"\cdot", "v", color=TXT).scale(1.6).move_to([0, 0.7, 0])
        src[0].set_color(COL_U7)
        src[2].set_color(COL_V7)
        flechas = [Arrow(src.get_top() + UP * 0.05, r.get_bottom() + DOWN * 0.1, buff=0.05, color=INK, stroke_width=3)
                   for r in (r1, r2, r3)]
        atrev = self.palabra("Idea atrevida", AMBAR, 1.0).move_to([0, -0.8, 0])
        q = MathTex("X", r"\cdot", "Y", "=", "?", color=TXT).scale(1.7).move_to([0, -0.8, 0])
        q[0].set_color(COL_U7)
        q[2].set_color(COL_V7)
        q[4].set_color(AMBAR)
        o = (-3.0, -3.2)
        fx = vec7(o, 2.2, 0, 1.0, COL_U7)
        fy = flecha_c(o, 2.4, 40, COL_V7)
        arco = arco7(o, 0, 40, 0.8, AMBAR)
        fy2 = flecha_c(o, 2.4, 90, COL_V7)
        sq = Square(side_length=0.3, color=AMBAR, stroke_width=3).move_to(np.array([o[0], o[1], 0]) + np.array([0.17, 0.17, 0]))
        tilde_ = tilde(VERDE, 1.4).move_to([3.4, -2.6, 0])
        with self.narrar("b2"):
            self.en("tres")
            self.play(FadeIn(r1), FadeIn(r2), FadeIn(r3), FadeIn(src), run_time=self.dur(0.6))
            self.en("todo")
            self.play(*[GrowArrow(f) for f in flechas], run_time=self.dur(0.8))
            self.en("atrevida")
            self.play(FadeOut(VGroup(r1, r2, r3, *flechas)), src.animate.move_to([0, 2.4, 0]), run_time=self.dur(0.5))
            self.pop(atrev)
            self.en("pregunta")
            self.play(FadeOut(atrev), FadeIn(q), run_time=self.dur(0.5))
            self.en("varaleat")
            self.play(src.animate.scale(0.7), run_time=self.dur(0.4))
            self.en("largo")
            self.play(GrowArrow(fx), GrowArrow(fy), run_time=self.dur(0.8))
            self.en("angulos")
            self.play(Create(arco), run_time=self.dur(0.5))
            self.en("perpend")
            self.play(FadeOut(fy), FadeOut(arco), GrowArrow(fy2), Create(sq), run_time=self.dur(0.9))
            self.en("puede")
            self.play(FadeIn(tilde_), run_time=self.dur(0.4))
            self.sfx("exito")

"""Escena 10 — Las dos perillas (número de trozos y duración de cada uno) y el compromiso."""
from comun.escena import *


class DosPerillas(EscenaCurso):
    ESCENA = "10"

    def construct(self):
        self.cuatro_y_uno()
        self.perillas()
        self.compromiso()
        self.wait(1.0)
        self.limpiar()

    def cuatro_y_uno(self):
        L = Lienzo(ancho=11.0, alto=1.0, t_rango=(0, 16), v_max=2.6, centro=(0, 3.2))
        t = np.linspace(0, 16, 400)
        traza_ = L.curva(t, 0.8 * serie(5, 400, 0.0), RUIDO, 2.4)
        cortes = VGroup(*[DashedLine(L.p(k, -1.2), L.p(k, 1.2), color=AMBAR, stroke_width=3) for k in (4, 8, 12)])
        fondos = VGroup(*[marco_t(L, 4 * k, 4 * k + 4, 1.2, AMBAR if k % 2 == 0 else CIAN, 0.12).set_stroke(width=0) for k in range(4)])
        e4 = MathTex(r"4\,\mathrm{s}", color=AMBAR).scale(0.8).move_to(L.p(2, 0) + DOWN * 0.95)
        F = Lienzo(ancho=10.5, alto=3.0, t_rango=(49, 51.5), v_max=2.0, centro=(0, -2.9))
        f_ = np.linspace(49, 51.5, 700)
        c4a = F.curva(f_, 0.9 * np.sinc(4 * (f_ - F_TONO_1)) ** 2, MEDIDA, 3.0, 0.9)
        c4b = F.curva(f_, 0.9 * np.sinc(4 * (f_ - F_TONO_2)) ** 2, MEDIDA, 3.0, 0.9)
        ancho4 = DoubleArrow(F.p(49.887, 0.45), F.p(50.113, 0.45), color=VERDE, buff=0, stroke_width=3, max_tip_length_to_length_ratio=0.3)
        l_ancho4 = MathTex(r"0{,}25\,\mathrm{Hz}", color=VERDE).scale(0.7).move_to(F.p(50.0, 0.45) + UP * 0.55 + LEFT * 1.0)
        fx, fy = medida_tonos(4, 4, 6)
        suma4 = F.curva(fx, fy, ESTIMACION, 4.0)
        ok = tilde(VERDE, 0.6).move_to([5.8, -1.3, 0])
        miniatura = VGroup(*[bosque_f(Lienzo(ancho=1.8, alto=0.8, t_rango=(0, 1), v_max=4.0, centro=(-3.3 + 2.2 * i, 1.3)),
                                      periodograma_blanco(200 + i, 30), MEDIDA, 1.8) for i in range(4)])
        entre2 = formula(r"\frac{1}{\sqrt{4}}", "=", r"\frac{1}{2}", escala=1.0, colores={0: AMBAR, 2: ERROR}).move_to([0, 0.1, 0])
        un = marco_t(L, 0, 16, 1.2, AMBAR, 0.15)
        e16 = MathTex(r"16\,\mathrm{s}", color=AMBAR).scale(0.8).move_to(L.p(8, 0) + DOWN * 0.95)
        c16a = F.curva(f_, 0.9 * np.sinc(16 * (f_ - F_TONO_1)) ** 2, MEDIDA, 3.0)
        c16b = F.curva(f_, 0.9 * np.sinc(16 * (f_ - F_TONO_2)) ** 2, MEDIDA, 3.0)
        fx2, fy2 = medida_tonos(16, 1, 8)
        bosque = F.curva(fx2, fy2, RUIDO, 2.2)
        with self.narrar("b1"):
            self.en("t4")
            self.play(Create(L.base()), Create(traza_), FadeIn(fondos), Create(cortes), FadeIn(e4), run_time=self.dur(1.0))
            self.en("cuarto_hz")
            self.play(Create(F.base()), Create(c4a), Create(c4b), Create(ancho4), FadeIn(l_ancho4), run_time=self.dur(0.9))
            self.en("separan")
            self.play(FadeOut(ancho4), FadeOut(l_ancho4), c4a.animate.set_stroke(opacity=0.3), c4b.animate.set_stroke(opacity=0.3),
                      Create(suma4), run_time=self.dur(0.7))
            self.pop(ok)
            self.en("solo4")
            self.play(FadeIn(miniatura, lag_ratio=0.2), run_time=self.dur(0.8))
            self.en("entre2")
            self.play(FadeIn(entre2), run_time=self.dur(0.6))
            self.en("tiembla")
            self.resaltar(suma4, color=ERROR, escala=1.03)
            self.en("un_trozo")
            self.play(FadeOut(fondos), FadeOut(cortes), FadeOut(e4), FadeOut(miniatura), FadeOut(entre2), FadeOut(ok),
                      FadeOut(c4a), FadeOut(c4b), FadeOut(suma4), FadeIn(un), FadeIn(e16), run_time=self.dur(0.9))
            self.en("excelente")
            self.play(Create(c16a), Create(c16b), run_time=self.dur(0.8))
            self.en("bosque")
            self.play(Create(bosque), run_time=self.dur(1.0))

    def perillas(self):
        Ma = Lienzo(ancho=5.0, alto=2.0, t_rango=(0, 1), v_max=3.0, centro=(-3.8, 2.0))
        Mb = Lienzo(ancho=5.0, alto=2.0, t_rango=(49, 51.5), v_max=2.0, centro=(3.8, 2.0))
        crudo = bosque_f(Ma, periodograma_blanco(8, 120), MEDIDA, 2.2)
        liso = bosque_f(Ma, periodograma_blanco(9, 120, 16), ESTIMACION, 3.5)
        f_ = np.linspace(49, 51.5, 400)
        borroso = Mb.curva(f_, tonos_medidos(f_, 1), MEDIDA, 3.5)
        nitido = Mb.curva(f_, tonos_medidos(f_, 4), ESTIMACION, 3.5)
        pa = perilla("número de trozos", AMBAR).move_to([-3.8, -0.4, 0])
        pb = perilla("duración de cada trozo", AMBAR).move_to([3.8, -0.4, 0])
        pa.aguja.move_to(pa.disco.get_center() + UP * 0.85 * 0.7 / 2, aligned_edge=DOWN)
        pb.aguja.move_to(pb.disco.get_center() + UP * 0.85 * 0.7 / 2, aligned_edge=DOWN)
        pa.aguja.put_start_and_end_on(pa.disco.get_center(), pa.disco.get_center() + UP * 0.6)
        pb.aguja.put_start_and_end_on(pb.disco.get_center(), pb.disco.get_center() + UP * 0.6)
        pa.aguja.rotate(-70 * DEGREES, about_point=pa.disco.get_center())
        pb.aguja.rotate(-70 * DEGREES, about_point=pb.disco.get_center())
        et_a = MathTex(r"M\to\mathrm{temblor}", color=ESTIMACION).scale(0.8).move_to([-3.8, 3.7, 0])
        et_b = MathTex(r"\text{duración}\to\text{resolución}", color=ESTIMACION).scale(0.8).move_to([3.8, 3.7, 0])
        prod = formula("M", r"\times", r"\text{duración}", "=", r"\text{grabación total}", escala=0.9,
                       colores={0: AMBAR, 2: AMBAR, 4: ESTIMACION}).move_to([0, -3.2, 0])
        bal = balancin().scale(0.7).move_to([0, -0.3, 0])
        with self.narrar("b2"):
            self.en("perillas")
            self.corte()
            self.play(FadeIn(pa), FadeIn(pb), FadeIn(pa.aguja), FadeIn(pb.aguja), run_time=self.dur(0.6))
            self.en("n_trozos")
            self.resaltar(pa.disco, color=AMBAR)
            self.en("tiembla2")
            self.play(FadeIn(et_a), Create(Ma.base()), Create(crudo), run_time=self.dur(0.6))
            self.play(Rotate(pa.aguja, 130 * DEGREES, about_point=pa.disco.get_center()), ReplacementTransform(crudo, liso),
                      run_time=self.dur(1.0))
            self.en("dur_trozo")
            self.resaltar(pb.disco, color=AMBAR)
            self.en("resol")
            self.play(FadeIn(et_b), Create(Mb.base()), Create(borroso), run_time=self.dur(0.6))
            self.play(Rotate(pb.aguja, 130 * DEGREES, about_point=pb.disco.get_center()), ReplacementTransform(borroso, nitido),
                      run_time=self.dur(1.2))
            self.en("producto")
            self.play(LaggedStart(*[FadeIn(prod[i]) for i in range(5)], lag_ratio=0.4), run_time=self.dur(2.2))
            self.en("balancin")
            self.pop(bal)

    def compromiso(self):
        Pl = Lienzo(ancho=6.0, alto=2.8, t_rango=(49, 51.5), v_max=2.0, centro=(-3.6, -0.6))
        Pr = Lienzo(ancho=6.0, alto=2.8, t_rango=(49, 51.5), v_max=2.0, centro=(3.6, -0.6))
        fl, yl = medida_tonos(1, 16, 7)
        fr, yr = medida_tonos(16, 1, 8)
        suave = Pl.curva(fl, yl, ESTIMACION, 4.0)
        nitidos = Pr.curva(fr, yr, MEDIDA, 2.2)
        x = cruz(ROJO, 2.2).move_to([0, -0.6, 0])
        flecha_g = flecha([0, 1.6, 0], [0, 2.6, 0], AMBAR)
        L = Lienzo(ancho=8.0, alto=0.9, t_rango=(0, 16), v_max=2.6, centro=(0, 3.4))
        traza_ = L.curva(np.linspace(0, 16, 300), 0.8 * serie(5, 300, 0.0), RUIDO, 2.4)
        ok = tilde(VERDE, 0.6).move_to([5.3, 3.4, 0])
        tercero = self.palabra("tercer problema", ROJO, 0.9).move_to([0, 3.2, 0])
        tij = tijera(TXT).scale(0.8).move_to([0, 1.5, 0])
        Lc = Lienzo(ancho=8.0, alto=0.9, t_rango=(0, 16), v_max=2.6, centro=(0, 0.2))
        izq = Lc.curva(np.linspace(0, 8, 150), 0.8 * serie(5, 300, 0.0)[:150], RUIDO, 2.6)
        der = Lc.curva(np.linspace(8, 16, 150), 0.8 * serie(5, 300, 0.0)[150:], RUIDO, 2.6)
        with self.narrar("b3"):
            self.en("suave")
            self.corte()
            self.play(Create(Pl.base()), Create(suave), run_time=self.dur(0.8))
            self.en("nitidos")
            self.play(Create(Pr.base()), Create(nitidos), run_time=self.dur(0.8))
            self.en("ninguna")
            self.pop(x)
            self.en("unica")
            self.play(FadeOut(x), Create(flecha_g), run_time=self.dur(0.5))
            self.en("mas_tiempo")
            self.play(Create(traza_), run_time=self.dur(0.9))
            self.pop(ok)
            self.en("tercero")
            self.corte()
            self.pop(tercero)
            self.en("tijeras")
            self.play(Create(izq), Create(der), run_time=self.dur(0.5))
            self.pop(tij)
            self.play(izq.animate.shift(LEFT * 0.35), der.animate.shift(RIGHT * 0.35), run_time=0.4)

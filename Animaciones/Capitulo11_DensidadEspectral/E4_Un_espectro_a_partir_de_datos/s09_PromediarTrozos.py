"""Escena 09 — Partir la grabación en trozos y promediar sus periodogramas: la varianza se divide entre M."""
from comun.escena import *


class PromediarTrozos(EscenaCurso):
    ESCENA = "09"

    def construct(self):
        self.partir()
        self.dieciseis()
        self.wait(1.0)
        self.limpiar()

    def partir(self):
        L = Lienzo(ancho=11.0, alto=1.1, t_rango=(0, 8), v_max=2.6, centro=(0, 3.1))
        t = np.linspace(0, 8, 320)
        traza_ = L.curva(t, 0.8 * serie(5, 320, 0.0), RUIDO, 2.4)
        cortes = VGroup(*[DashedLine(L.p(k, -1.3), L.p(k, 1.3), color=AMBAR, stroke_width=2.5) for k in range(1, 8)])
        fondos = VGroup(*[marco_t(L, k, k + 1, 1.3, AMBAR if k % 2 == 0 else CIAN, 0.12).set_stroke(width=0) for k in range(8)])
        minis = []
        for i in range(8):
            M = Lienzo(ancho=1.2, alto=0.9, t_rango=(0, 1), v_max=4.0, centro=(-4.9 + i * 1.4, 1.0))
            minis.append(VGroup(M.base(), bosque_f(M, periodograma_blanco(100 + i, 30), MEDIDA, 1.8)))
        P = Lienzo(ancho=9.0, alto=2.6, t_rango=(0, 1), v_max=3.0, centro=(0, -3.2))
        plano = P.curva([0, 1], [1, 1], SENAL, 4)
        prom = bosque_f(P, periodograma_blanco(5, 120, 8), ESTIMACION, 4.0)
        o = self.preparar_cap7()
        with self.narrar("b1"):
            self.en("partir")
            self.play(Create(L.base()), Create(traza_), run_time=self.dur(0.7))
            self.play(FadeIn(fondos), Create(cortes), run_time=self.dur(0.7))
            self.en("cadauno")
            self.play(LaggedStart(*[FadeIn(m) for m in minis], lag_ratio=0.2), run_time=self.dur(1.4))
            self.en("promedio")
            self.play(Create(P.base()), Create(plano), Create(prom), run_time=self.dur(1.3))
            self.animar_cap7(o)

    def preparar_cap7(self):
        cap7 = etiqueta("Capítulo 7", INK, 0.55).move_to([-5.6, 3.4, 0])
        f = formula(r"\mathrm{Var}", r"(\bar X)", "=", r"\sigma^2", r"\,/\,n", escala=1.1,
                    colores={3: AMBAR}).move_to([0, 2.2, 0])
        fM = formula(r"\mathrm{Var}", r"(\bar X)", "=", r"\sigma^2", r"\,/\,M", escala=1.1,
                     colores={3: AMBAR, 4: ESTIMACION}).move_to([0, 2.2, 0])
        g = formula(r"\sigma_{\bar X}", "=", r"\sigma", r"\,/\,\sqrt{n}", escala=1.1, colores={2: AMBAR}).move_to([0, 0.6, 0])
        aqui = etiqueta("cada trozo es una medida", AMBAR, 0.5).move_to([4.9, 2.2, 0])
        B = Lienzo(ancho=7.0, alto=2.2, t_rango=(0, 1), v_max=2.0, centro=(0, -2.3))
        media = DashedLine(B.p(0, 0), B.p(1, 0), color=SENAL, stroke_width=3)
        ancha = Rectangle(width=7.0, height=1.6, stroke_width=0).set_fill(AMBAR, 0.22).move_to(B.p(0.5, 0))
        estrecha = Rectangle(width=7.0, height=0.5, stroke_width=0).set_fill(AMBAR, 0.35).move_to(B.p(0.5, 0))
        return dict(cap7=cap7, f=f, fM=fM, g=g, aqui=aqui, B=B, media=media, ancha=ancha, estrecha=estrecha)

    def animar_cap7(self, o):
        cap7, f, fM, g, aqui, B, media, ancha, estrecha = (o[k] for k in ('cap7','f','fM','g','aqui','B','media','ancha','estrecha'))
        self.en("cap7")
        self.corte()
        self.play(FadeIn(cap7), run_time=0.3)
        self.en("varprom")
        self.play(FadeIn(f[0]), FadeIn(f[1]), FadeIn(f[2]), run_time=self.dur(0.7))
        self.en("de_una")
        self.play(FadeIn(f[3]), run_time=0.4)
        self.en("entre_n")
        self.play(FadeIn(f[4]), run_time=0.4)
        self.en("raiz")
        self.play(FadeIn(g), Create(media), FadeIn(ancha), run_time=self.dur(0.8))
        self.play(ReplacementTransform(ancha, estrecha), run_time=self.dur(1.0))
        self.en("aqui")
        self.play(FadeIn(aqui), run_time=0.4)
        self.en("emetrozos")
        self.play(ReplacementTransform(f[4], fM[4]), run_time=self.dur(0.6))
        self.en("entre_m")
        self.resaltar(fM[4], color=ESTIMACION)

    def dieciseis(self):
        L = Lienzo(ancho=11.0, alto=1.0, t_rango=(0, 16), v_max=2.6, centro=(0, 3.2))
        t = np.linspace(0, 16, 400)
        traza_ = L.curva(t, 0.8 * serie(5, 400, 0.0), RUIDO, 2.4)
        e16 = MathTex(r"16\,\mathrm{s}", color=AMBAR).scale(0.8).move_to([-6.0, 3.2, 0])
        cortes = VGroup(*[DashedLine(L.p(k, -1.2), L.p(k, 1.2), color=AMBAR, stroke_width=2) for k in range(1, 16)])
        trozo = marco_t(L, 0, 1, 1.2, AMBAR, 0.25)
        e1s = MathTex(r"1\,\mathrm{s}", color=AMBAR).scale(0.7).move_to(L.p(0.5, 0) + DOWN * 0.85)
        r = formula(r"\frac{1}{\sqrt{16}}", "=", r"\frac{1}{4}", escala=1.1, colores={0: AMBAR, 2: ESTIMACION}).move_to([0, 1.2, 0])
        Pa = Lienzo(ancho=5.6, alto=2.4, t_rango=(0, 1), v_max=3.0, centro=(-3.4, -3.1))
        plano = Pa.curva([0, 1], [1, 1], SENAL, 4)
        crudo = bosque_f(Pa, periodograma_blanco(8, 120), MEDIDA, 2.2)
        liso = bosque_f(Pa, periodograma_blanco(9, 120, 16), ESTIMACION, 4.0)
        e_un_cuarto = etiqueta("tiembla ¼", ESTIMACION, 0.55).move_to([-3.4, -0.6, 0])
        e_suave = etiqueta("suave", ESTIMACION, 0.55).move_to([-3.4, -0.6, 0])
        Pb = Lienzo(ancho=5.6, alto=2.4, t_rango=(49, 51.5), v_max=2.0, centro=(3.4, -3.1))
        ray1 = VGroup(Line(Pb.p(F_TONO_1, 0), Pb.p(F_TONO_1, 1.5), color=SENAL, stroke_width=6), Dot(Pb.p(F_TONO_1, 1.5), radius=0.08, color=SENAL))
        ray2 = VGroup(Line(Pb.p(F_TONO_2, 0), Pb.p(F_TONO_2, 1.5), color=SENAL, stroke_width=6), Dot(Pb.p(F_TONO_2, 1.5), radius=0.08, color=SENAL))
        tonos_et = etiqueta("50 y 50,5 Hz", INK, 0.5).move_to([3.4, -3.6, 0])
        ancho_hz = DoubleArrow(Pb.p(49.55, 0.45), Pb.p(50.45, 0.45), color=VERDE, buff=0, stroke_width=3, max_tip_length_to_length_ratio=0.15)
        e_hz = MathTex(r"1\,\mathrm{Hz}", color=VERDE).scale(0.7).move_to(Pb.p(50.0, 0.45) + UP * 0.4 + LEFT * 1.5)
        f_, y_ = medida_tonos(1, 16, 5)
        bulto = Pb.curva(f_, y_, ESTIMACION, 4.5)
        with self.narrar("b2"):
            self.en("grab16")
            self.corte()
            self.play(Create(L.base()), Create(traza_), FadeIn(e16), run_time=self.dur(0.9))
            self.en("t16")
            self.play(Create(cortes), run_time=self.dur(0.5))
            self.play(FadeIn(trozo), FadeIn(e1s), run_time=0.3)
            self.en("raiz16")
            self.play(FadeIn(r[0]), run_time=0.4)
            self.en("cuatro")
            self.play(FadeIn(r[1]), FadeIn(r[2]), run_time=0.4)
            self.en("cuarto")
            self.play(Create(Pa.base()), Create(plano), Create(crudo), run_time=self.dur(0.6))
            self.play(ReplacementTransform(crudo, liso), FadeIn(e_un_cuarto), run_time=self.dur(0.9))
            self.en("suave")
            self.play(ReplacementTransform(e_un_cuarto, e_suave), run_time=0.3)
            self.resaltar(liso, color=ESTIMACION, escala=1.04)
            self.en("cada_trozo")
            self.resaltar(trozo, color=AMBAR)
            self.en("un_hz")
            self.play(Create(Pb.base()), Create(ancho_hz), FadeIn(e_hz), run_time=self.dur(0.7))
            self.en("tonos")
            self.play(Create(ray1), Create(ray2), FadeIn(tonos_et), run_time=self.dur(0.7))
            self.en("fundidos")
            self.play(FadeOut(ray1), FadeOut(ray2), FadeOut(ancho_hz), FadeOut(e_hz), Create(bulto), run_time=self.dur(0.9))

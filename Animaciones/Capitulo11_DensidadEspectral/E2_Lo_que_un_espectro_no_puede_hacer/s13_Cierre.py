"""Escena 13 — Cierre: resumen y anuncio del E3, «El color del ruido»."""
from comun.escena import *


class Cierre(EscenaCurso):
    ESCENA = "13"

    def construct(self):
        P = Lienzo(ancho=5.4, alto=2.2, t_rango=(-12, 12), v_max=1.2, centro=(-3.6, 1.5))
        ej = ejes_L(P, -0.1, 1.15)
        psd = curva_f(P, psd_tele, -12, 12, AMBAR, 5)
        ok1 = tilde(VERDE, 0.4).move_to([-6.2, 2.9, 0])
        sim = DashedLine(P.p(0, -0.1), P.p(0, 1.15), color=INK, stroke_width=2.5)
        reglas = etiqueta("≥ 0 · real · par", AMBAR, 0.6).move_to([-3.6, -0.15, 0])
        r04 = VGroup(MathTex(r"\rho=0{,}4", color=TXT).scale(0.9), tilde(VERDE, 0.35)).arrange(RIGHT, buff=0.3).move_to([3.6, 2.7, 0])
        r06 = VGroup(MathTex(r"\rho=0{,}6", color=TXT).scale(0.9), cruz(ROJO, 0.5)).arrange(RIGHT, buff=0.3).move_to([3.6, 1.6, 0])
        ap = VGroup(MathTex(r"1+0{,}8\cos\Omega", color=AMBAR).scale(0.9), tilde(VERDE, 0.35)).arrange(RIGHT, buff=0.3).move_to([3.6, 0.4, 0])
        mon = moneda("", AMBAR).scale(0.8).move_to([-4.6, -2.4, 0])
        blq = BloqueLTI("h", centro=(-1.4, -2.4), ancho=1.8, alto=1.1, largo=1.0)
        Lp = Lienzo(ancho=3.2, alto=1.1, t_rango=(0, 1), v_max=2.4, centro=(3.2, -2.4))
        t = np.linspace(0, 1, 140)
        proc = Lp.curva(t, 0.9 * serie(23, 140, 0.8), SENAL, 3.5)
        # un eje vacío con una pregunta
        E = Lienzo(ancho=5.0, alto=2.4, t_rango=(-12, 12), v_max=1.2, centro=(0.0, 0.5))
        ej_e = ejes_L(E, -0.1, 1.15)
        interr = MathTex("?", color=AMBAR).scale(2.4).move_to([0, 1.2, 0])
        # sin memoria / memoria total
        Ls = Lienzo(ancho=4.2, alto=1.8, t_rango=(-12, 12), v_max=1.3, centro=(-3.7, 0.9))
        plano = Ls.curva([-12, 12], [0.8, 0.8], SENAL, 5)
        bar = Line(Ls.p(0, -1.0), Ls.p(0, 0.2), color=RUIDO, stroke_width=8).shift(DOWN * 1.2)
        La = Lienzo(ancho=4.2, alto=1.8, t_rango=(-12, 12), v_max=1.3, centro=(3.7, 0.9))
        rayas = VGroup(Line(La.p(-4, 0), La.p(-4, 1.1), color=AMBAR, stroke_width=8),
                       Line(La.p(4, 0), La.p(4, 1.1), color=AMBAR, stroke_width=8))
        coseno_ = La.curva(np.linspace(-12, 12, 200), 0.4 * np.cos(2 * np.linspace(-12, 12, 200)), RUIDO, 3).shift(DOWN * 1.5)
        prox = etiqueta("Próximo episodio", INK, 0.6).move_to([0, 1.7, 0])
        a = self.palabra("El color", TXT, 1.8).move_to([0, 0.4, 0])
        b = self.palabra("del ruido", AMBAR, 1.8).move_to([0, -1.2, 0])
        colores = VGroup(*[Rectangle(width=1.1, height=0.28, stroke_width=0).set_fill(c, 1)
                           for c in (ROJO, AMBAR, "#e8d44d", VERDE, CIAN, AZUL, MAGENTA)]).arrange(RIGHT, buff=0.08).move_to([0, -2.7, 0])
        with self.narrar("b1"):
            self.en("nunca")
            self.play(Create(ej), Create(psd), FadeIn(ok1), run_time=self.dur(0.9))
            self.en("realpar")
            self.play(Create(sim), run_time=0.4)
            self.en("reglas")
            self.pop(reglas)
            self.en("si")
            self.play(FadeIn(r04), run_time=0.4)
            self.en("no")
            self.play(FadeIn(r06), run_time=0.4)
            self.en("aprueba")
            self.play(FadeIn(ap), run_time=0.5)
            self.en("fabricar")
            self.play(FadeIn(mon), FadeIn(blq), Create(Lp.base()), Create(proc), run_time=self.dur(1.2))
            self.en("comoes")
            self.corte()
            self.play(Create(ej_e), run_time=0.4)
            self.pop(interr)
            self.en("sinmemoria")
            self.corte()
            self.play(Create(Ls.base()), Create(plano), Create(bar), run_time=self.dur(0.9))
            self.en("todo")
            self.play(Create(La.base()), Create(rayas), Create(coseno_), run_time=self.dur(0.9))
            self.en("titulo_e3")
            self.limpiar(0.25)
            self.play(FadeIn(prox), run_time=0.3)
            self.pop(a, b)
            self.play(FadeIn(colores), run_time=0.5)
        self.wait(1.0)
        self.limpiar()
